using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Godot;

namespace ProjectD;

/// <summary>
/// Writes a <see cref="Graybox"/> as Godot scene text (raid map standard s1). The result is a root node with a
/// navigation region of static boxes plus the marker groups the raid code already reads; it is regenerated, never
/// hand-edited.
/// </summary>
public static class GrayboxTscn
{
	private static readonly Dictionary<string, Color> Colors = new()
	{
		["ground"] = new Color(0.33f, 0.36f, 0.26f), ["cutfloor"] = new Color(0.25f, 0.22f, 0.18f), ["mound"] = new Color(0.42f, 0.38f, 0.27f),
		["wall"] = new Color(0.55f, 0.55f, 0.53f), ["slab"] = new Color(0.45f, 0.45f, 0.44f), ["roof"] = new Color(0.32f, 0.32f, 0.33f),
		["stair"] = new Color(0.5f, 0.5f, 0.47f), ["cover"] = new Color(0.45f, 0.4f, 0.28f), ["vehicle"] = new Color(0.3f, 0.34f, 0.25f),
		["fence"] = new Color(0.4f, 0.4f, 0.42f), ["tree"] = new Color(0.2f, 0.35f, 0.18f), ["prop"] = new Color(0.5f, 0.42f, 0.32f),
	};

	private const string PlayerSpawn = "res://scripts/raid/PlayerSpawnPoint.cs";
	private const string AiSpawn = "res://scripts/raid/AiSpawnPoint.cs";
	private const string LootSpot = "res://scripts/raid/LootSpot.cs";
	private const string Extraction = "res://scripts/raid/ExtractionZone.cs";
	private const string QuestZone = "res://scripts/raid/QuestZone.cs";
	private const string WaveSpawn = "res://scripts/raid/WaveSpawnPoint.cs";
	private const string MineField = "res://scripts/raid/MineField.cs";
	private const string SafeLane = "res://scripts/raid/SafeLanePoint.cs";
	private const string BossRoute = "res://scripts/raid/BossRoutePoint.cs";
	private const string TransitZone = "res://scripts/raid/TransitZone.cs";
	private const string Arrival = "res://scripts/raid/ArrivalPoint.cs";
	private const string LockedDoor = "res://scripts/raid/LockedDoor.cs";
	private static readonly Vector3 DoorDefault = new(0.3f, 2.6f, 3f);
	private const string Foliage = "res://scripts/world/FoliageVolume.cs";
	private static readonly Vector3 FoliageDefault = new(8f, 3f, 8f);

	// "+ 0f" turns a negative zero into a plain zero
	private static string F(float v) => (v + 0f).ToString("0.####", CultureInfo.InvariantCulture);
	private static string V3(Vector3 v) => $"Vector3({F(v.X)}, {F(v.Y)}, {F(v.Z)})";
	private static string Q(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

	private static string Transform(Vector3 p, float yawDeg)
	{
		var r = Mathf.DegToRad(yawDeg);
		var (c, s) = (Mathf.Cos(r), Mathf.Sin(r));
		return $"Transform3D({F(c)}, 0, {F(s)}, 0, 1, 0, {F(-s)}, 0, {F(c)}, {F(p.X)}, {F(p.Y)}, {F(p.Z)})";
	}

	private static Vector3 SizeProp(GrayMarker m, Vector3 fallback)
		=> new LayoutMarker { Props = m.Props.ToDictionary(p => p.Key, p => p.Value) }.SizeOr(fallback);

	private static string Prop(GrayMarker m, string key, string fallback = "") => m.Props.TryGetValue(key, out var v) ? v : fallback;

	public static string Write(Graybox g)
	{
		var shapes = g.Boxes.Select(b => b.Size).Distinct().ToList();
		var meshes = g.Boxes.Select(b => (b.Size, b.Material)).Distinct().ToList();
		var materials = g.Boxes.Select(b => b.Material).Distinct().ToList();
		var sb = new StringBuilder();
		sb.Append($"[gd_scene load_steps={4 + shapes.Count + meshes.Count + materials.Count} format=3]\n\n");
		sb.Append("; Generated by GrayboxTscn from data/maps layout. Do not edit: regenerate instead.\n\n");
		var scripts = new Dictionary<string, string> { [PlayerSpawn] = "ps", [AiSpawn] = "ai", [LootSpot] = "lt", [Extraction] = "ex", [QuestZone] = "qz", [Foliage] = "fo", [WaveSpawn] = "wv", [MineField] = "mf", [SafeLane] = "sl", [BossRoute] = "br", [TransitZone] = "tz", [Arrival] = "ar", [LockedDoor] = "ld" };
		foreach (var (path, id) in scripts)
			sb.Append($"[ext_resource type=\"Script\" path=\"{path}\" id=\"{id}\"]\n");
		sb.Append("\n[sub_resource type=\"NavigationMesh\" id=\"nav\"]\ncell_size = 0.5\ncell_height = 0.25\nagent_height = 2.0\nagent_radius = 0.5\n"
			+ "agent_max_climb = 0.5\nagent_max_slope = 45.0\ngeometry_parsed_geometry_type = 1\n\n");
		foreach (var m in materials)
		{
			var c = Colors.TryGetValue(m, out var col) ? col : new Color(0.6f, 0.6f, 0.6f);
			sb.Append($"[sub_resource type=\"StandardMaterial3D\" id=\"mat_{m}\"]\nalbedo_color = Color({F(c.R)}, {F(c.G)}, {F(c.B)}, 1)\n\n");
		}
		var foliage = g.Markers.Where(m => m.Type == "foliage").Select(m => SizeProp(m, FoliageDefault)).Distinct().ToList();
		if (foliage.Count > 0)
			sb.Append("[sub_resource type=\"StandardMaterial3D\" id=\"mat_foliage\"]\nalbedo_color = Color(0.2, 0.45, 0.2, 0.4)\ntransparency = 1\n\n");
		for (var i = 0; i < foliage.Count; i++)
			sb.Append($"[sub_resource type=\"BoxShape3D\" id=\"fshape_{i}\"]\nsize = {V3(foliage[i])}\n\n[sub_resource type=\"BoxMesh\" id=\"fmesh_{i}\"]\nmaterial = SubResource(\"mat_foliage\")\nsize = {V3(foliage[i])}\n\n");
		var doors = g.Markers.Where(m => m.Type == "lock").Select(m => SizeProp(m, DoorDefault)).Distinct().ToList();
		if (doors.Count > 0)
			sb.Append("[sub_resource type=\"StandardMaterial3D\" id=\"mat_door\"]\nalbedo_color = Color(0.4, 0.3, 0.2, 1)\n\n");
		for (var i = 0; i < doors.Count; i++)
			sb.Append($"[sub_resource type=\"BoxShape3D\" id=\"dshape_{i}\"]\nsize = {V3(doors[i])}\n\n[sub_resource type=\"BoxMesh\" id=\"dmesh_{i}\"]\nmaterial = SubResource(\"mat_door\")\nsize = {V3(doors[i])}\n\n");
		for (var i = 0; i < shapes.Count; i++)
			sb.Append($"[sub_resource type=\"BoxShape3D\" id=\"shape_{i}\"]\nsize = {V3(shapes[i])}\n\n");
		for (var i = 0; i < meshes.Count; i++)
			sb.Append($"[sub_resource type=\"BoxMesh\" id=\"mesh_{i}\"]\nmaterial = SubResource(\"mat_{meshes[i].Material}\")\nsize = {V3(meshes[i].Size)}\n\n");

		var root = GrayboxBuilder.Safe(g.MapId) + "_graybox";
		sb.Append($"[node name=\"{root}\" type=\"Node3D\"]\n\n");
		sb.Append("[node name=\"Geometry\" type=\"NavigationRegion3D\" parent=\".\"]\nnavigation_mesh = SubResource(\"nav\")\n\n");
		foreach (var group in new[] { "Ground", "Terrain", "Buildings", "Props" })
		{
			if (!g.Boxes.Any(b => b.Group == group))
				continue;
			sb.Append($"[node name=\"{group}\" type=\"Node3D\" parent=\"Geometry\"]\n\n");
			foreach (var b in g.Boxes.Where(b => b.Group == group))
			{
				var parent = $"Geometry/{group}";
				sb.Append($"[node name=\"{b.Name}\" type=\"StaticBody3D\" parent=\"{parent}\"]\ntransform = {Transform(b.Center, b.RotYDeg)}\n\n");
				sb.Append($"[node name=\"Shape\" type=\"CollisionShape3D\" parent=\"{parent}/{b.Name}\"]\nshape = SubResource(\"shape_{shapes.IndexOf(b.Size)}\")\n\n");
				sb.Append($"[node name=\"Mesh\" type=\"MeshInstance3D\" parent=\"{parent}/{b.Name}\"]\nmesh = SubResource(\"mesh_{meshes.IndexOf((b.Size, b.Material))}\")\n\n");
			}
		}

		var sections = new (string Name, string[] Types)[]
		{
			("Spawns", new[] { "playerSpawn" }), ("AiSpawns", new[] { "aiSpawn" }), ("LootSpots", new[] { "loot" }),
			("Extractions", new[] { "extract" }), ("QuestZones", new[] { "questZone" }), ("Foliage", new[] { "foliage" }), ("WaveSpawns", new[] { "waveSpawn" }), ("Locks", new[] { "lock" }),
		};
		var handled = sections.SelectMany(s => s.Types).ToHashSet();
		foreach (var (name, types) in sections)
		{
			if (!g.Markers.Any(m => types.Contains(m.Type)))
				continue;
			sb.Append($"[node name=\"{name}\" type=\"Node3D\" parent=\".\"]\n\n");
			foreach (var m in g.Markers.Where(m => types.Contains(m.Type)))
			{
				if (m.Type == "foliage")
					FoliageNode(sb, m, foliage.IndexOf(SizeProp(m, FoliageDefault)));
				else if (m.Type == "lock")
					LockNode(sb, m, doors.IndexOf(SizeProp(m, DoorDefault)));
				else
					MarkerNode(sb, m, name);
			}
		}
		var others = g.Markers.Where(m => !handled.Contains(m.Type)).ToList();
		if (others.Count > 0)
		{
			sb.Append("[node name=\"Markers\" type=\"Node3D\" parent=\".\"]\n\n");
			foreach (var m in others)
				MarkerNode(sb, m, "Markers");
		}
		return sb.ToString();
	}

	/// <summary>A locked door: a solid box that <c>LockedDoor</c> slides away when its key is used.</summary>
	private static void LockNode(StringBuilder sb, GrayMarker m, int index)
	{
		var size = SizeProp(m, DoorDefault);
		var at = new Vector3(m.Position.X, m.Position.Y + size.Y / 2f, m.Position.Z);
		sb.Append($"[node name=\"{m.Name}\" type=\"StaticBody3D\" parent=\"Locks\"]\ntransform = {Transform(at, m.YawDeg)}\nscript = ExtResource(\"ld\")\n");
		sb.Append($"KeyId = {Q(Prop(m, "key"))}\nOpenLift = {F(size.Y)}\nTitleKey = {Q("lock." + Prop(m, "title", "door"))}\nmetadata/layout_type = \"lock\"\n\n");
		sb.Append($"[node name=\"Shape\" type=\"CollisionShape3D\" parent=\"Locks/{m.Name}\"]\nshape = SubResource(\"dshape_{index}\")\n\n");
		sb.Append($"[node name=\"Mesh\" type=\"MeshInstance3D\" parent=\"Locks/{m.Name}\"]\nmesh = SubResource(\"dmesh_{index}\")\n\n");
	}

	/// <summary>A foliage volume (sight-thinning box on its own physics layer) with a faint green mesh for the blockout.</summary>
	private static void FoliageNode(StringBuilder sb, GrayMarker m, int index)
	{
		var at = new Vector3(m.Position.X, m.Position.Y + SizeProp(m, FoliageDefault).Y / 2f, m.Position.Z);
		sb.Append($"[node name=\"{m.Name}\" type=\"StaticBody3D\" parent=\"Foliage\"]\ntransform = {Transform(at, 0f)}\ncollision_layer = 32\ncollision_mask = 0\nscript = ExtResource(\"fo\")\n");
		sb.Append($"metadata/layout_type = \"foliage\"\n\n[node name=\"Shape\" type=\"CollisionShape3D\" parent=\"Foliage/{m.Name}\"]\nshape = SubResource(\"fshape_{index}\")\n\n");
		sb.Append($"[node name=\"Mesh\" type=\"MeshInstance3D\" parent=\"Foliage/{m.Name}\"]\nmesh = SubResource(\"fmesh_{index}\")\n\n");
	}

	private static void MarkerNode(StringBuilder sb, GrayMarker m, string parent)
	{
		var type = m.Type is "extract" or "questZone" or "minefield" or "tunnel" or "transit" ? "Node3D" : "Marker3D";
		sb.Append($"[node name=\"{m.Name}\" type=\"{type}\" parent=\"{parent}\"]\ntransform = {Transform(m.Position, m.YawDeg)}\n");
		switch (m.Type)
		{
			case "playerSpawn":
				sb.Append("script = ExtResource(\"ps\")\n");
				break;
			case "aiSpawn":
				sb.Append($"script = ExtResource(\"ai\")\nPresetId = {Q(Prop(m, "preset", "bandit"))}\n");
				if (m.Props.ContainsKey("rollGroup"))
					sb.Append($"RollGroup = {Q(Prop(m, "rollGroup"))}\nRollMin = {Prop(m, "rollMin", "0")}\nRollMax = {Prop(m, "rollMax", "0")}\n");
				if (m.Props.ContainsKey("patrolRadius"))
					sb.Append($"PatrolRadius = {Prop(m, "patrolRadius")}\n");
				break;
			case "minefield":
				sb.Append($"script = ExtResource(\"mf\")\nSize = {V3(SizeProp(m, new Vector3(38f, 2f, 80f)))}\n");
				break;
			case "safeLane":
				sb.Append($"script = ExtResource(\"sl\")\nLane = {Q(Prop(m, "lane"))}\nOrder = {Prop(m, "order", "0")}\n");
				break;
			case "bossRoute":
				sb.Append($"script = ExtResource(\"br\")\nSquad = {Q(Prop(m, "squad"))}\nOrder = {Prop(m, "order", "0")}\n");
				break;
			case "tunnel":
			case "transit":
				var road = m.Type == "transit";
				sb.Append($"script = ExtResource(\"tz\")\nZoneId = {Q(m.Name)}\nKind = {(road ? 1 : 0)}\nSeconds = {Prop(m, "seconds", road ? "6" : "4")}\nCost = {Prop(m, "cost", "0")}\n"
					+ $"PairId = {Q(Prop(m, "pair"))}\nDestination = {Q(Prop(m, "to"))}\nRequiredItemId = {Q(Prop(m, "item"))}\nSize = {V3(SizeProp(m, new Vector3(6f, 3f, 6f)))}\n");
				break;
			case "arrival":
				sb.Append($"script = ExtResource(\"ar\")\nFrom = {Q(Prop(m, "from"))}\n");
				break;
			case "waveSpawn":
				sb.Append($"script = ExtResource(\"wv\")\nWave = {Q(Prop(m, "wave", "patrol"))}\nAtMinutes = {Q(Prop(m, "atMin", "8"))}\n"
					+ $"PresetId = {Q(Prop(m, "preset", "bandit"))}\nCount = {Prop(m, "count", "3")}\nSide = {Q(Prop(m, "side"))}\n");
				break;
			case "loot":
				sb.Append($"script = ExtResource(\"lt\")\nTier = {Array.IndexOf(MapLayout.LootTiers, Prop(m, "tier"))}\n");
				break;
			case "extract":
				var kind = Prop(m, "kind") switch { "item" => 1, "paid" => 2, _ => 0 };
				var size = SizeProp(m, new Vector3(6f, 3f, 6f));
				sb.Append($"script = ExtResource(\"ex\")\nZoneId = {Q(m.Name)}\nKind = {kind}\nSeconds = {Prop(m, "seconds", "6")}\n");
				if (kind == 1) sb.Append($"RequiredItemId = {Q(Prop(m, "item"))}\n");
				if (kind == 2) sb.Append($"Cost = {Prop(m, "cost", "0")}\n");
				sb.Append($"Size = {V3(size)}\n");
				break;
			case "questZone":
				sb.Append($"script = ExtResource(\"qz\")\nZoneId = {Q(m.Name)}\nSize = {V3(SizeProp(m, new Vector3(6f, 3f, 6f)))}\n");
				break;
		}
		sb.Append($"metadata/layout_type = {Q(m.Type)}\n");
		foreach (var (key, value) in m.Props.OrderBy(p => p.Key, StringComparer.Ordinal))
			sb.Append($"metadata/{key} = {Q(value)}\n");
		sb.Append('\n');
	}
}
